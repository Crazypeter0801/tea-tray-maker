#!/usr/bin/env python3
"""Render the actual STL using a depth buffer; this is not a print/photo preview."""
import argparse
from pathlib import Path
import vtk

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('stl')
p.add_argument('--out', required=True)
a = p.parse_args()
reader = vtk.vtkSTLReader()
reader.SetFileName(a.stl)
reader.Update()
if reader.GetOutput().GetNumberOfPoints() == 0:
    raise ValueError('Empty STL')
b = reader.GetOutput().GetBounds()
center = ((b[0]+b[1])/2, (b[2]+b[3])/2, (b[4]+b[5])/2)
span = max(b[1]-b[0], b[3]-b[2])
window = vtk.vtkRenderWindow()
window.SetOffScreenRendering(1)
window.SetSize(1600, 650)
for index, position, up, title in (
    (0, (center[0],center[1],center[2]+span*3), (0,1,0), 'Top | actual STL'),
    (1, (center[0]+span,center[1]-span,center[2]+span*1.3), (0,0,1), 'Isometric | actual STL')):
    renderer = vtk.vtkRenderer()
    renderer.SetViewport(index*.5, 0, (index+1)*.5, 1)
    renderer.SetBackground(1,1,1)
    mapper = vtk.vtkPolyDataMapper()
    mapper.SetInputConnection(reader.GetOutputPort())
    actor = vtk.vtkActor()
    actor.SetMapper(mapper)
    actor.GetProperty().SetColor(.55,.66,.70)
    actor.GetProperty().SetAmbient(.25)
    actor.GetProperty().SetDiffuse(.75)
    renderer.AddActor(actor)
    edges = vtk.vtkFeatureEdges()
    edges.SetInputConnection(reader.GetOutputPort())
    edges.SetFeatureAngle(35)
    edges.BoundaryEdgesOn()
    edges.FeatureEdgesOn()
    edges.ManifoldEdgesOff()
    edges.NonManifoldEdgesOff()
    edge_mapper = vtk.vtkPolyDataMapper()
    edge_mapper.SetInputConnection(edges.GetOutputPort())
    edge_mapper.ScalarVisibilityOff()
    edge_actor = vtk.vtkActor()
    edge_actor.SetMapper(edge_mapper)
    edge_actor.GetProperty().SetColor(.25,.34,.38)
    edge_actor.GetProperty().SetLineWidth(1)
    renderer.AddActor(edge_actor)
    text = vtk.vtkTextActor()
    text.SetInput(title)
    text.SetPosition(30,610)
    text.GetTextProperty().SetColor(.12,.15,.18)
    text.GetTextProperty().SetFontSize(22)
    renderer.AddViewProp(text)
    camera = renderer.GetActiveCamera()
    camera.SetPosition(*position)
    camera.SetFocalPoint(*center)
    camera.SetViewUp(*up)
    camera.ParallelProjectionOn()
    renderer.ResetCamera()
    camera.Zoom(1.15)
    window.AddRenderer(renderer)
window.Render()
capture = vtk.vtkWindowToImageFilter()
capture.SetInput(window)
capture.ReadFrontBufferOff()
capture.Update()
Path(a.out).parent.mkdir(parents=True, exist_ok=True)
writer = vtk.vtkPNGWriter()
writer.SetFileName(a.out)
writer.SetInputConnection(capture.GetOutputPort())
writer.Write()
window.Finalize()
